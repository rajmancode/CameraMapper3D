package com.cameramapper3d.core

import java.io.BufferedOutputStream
import java.io.BufferedWriter
import java.io.DataInputStream
import java.io.IOException
import java.io.InputStream
import java.io.OutputStream
import java.io.OutputStreamWriter
import java.nio.ByteBuffer
import java.nio.ByteOrder
import java.util.Locale

/**
 * Writes binary little-endian PLY with positions, normals and vertex colours.
 * PLY keeps colour and opens in MeshLab, CloudCompare, Blender and most CAD/BIM point-cloud tools.
 */
object PlyWriter {
    fun write(mesh: MeshData, out: OutputStream, comment: String? = null) {
        val bos = BufferedOutputStream(out, 1 shl 16)
        val header = buildString {
            append("ply\n")
            append("format binary_little_endian 1.0\n")
            append("comment Generated by CameraMapper3D. Units: metres. Y is up.\n")
            if (comment != null) append("comment ").append(comment.replace('\n', ' ')).append('\n')
            append("element vertex ").append(mesh.vertexCount).append('\n')
            append("property float x\nproperty float y\nproperty float z\n")
            append("property float nx\nproperty float ny\nproperty float nz\n")
            append("property uchar red\nproperty uchar green\nproperty uchar blue\n")
            append("element face ").append(mesh.triangleCount).append('\n')
            append("property list uchar int vertex_indices\n")
            append("end_header\n")
        }
        bos.write(header.toByteArray(Charsets.US_ASCII))

        val vbuf = ByteBuffer.allocate(27).order(ByteOrder.LITTLE_ENDIAN)
        for (i in 0 until mesh.vertexCount) {
            vbuf.clear()
            for (a in 0 until 3) vbuf.putFloat(mesh.positions[i * 3 + a])
            for (a in 0 until 3) vbuf.putFloat(mesh.normals[i * 3 + a])
            for (a in 0 until 3) vbuf.put(mesh.colors[i * 3 + a])
            bos.write(vbuf.array(), 0, 27)
        }
        val fbuf = ByteBuffer.allocate(13).order(ByteOrder.LITTLE_ENDIAN)
        for (t in 0 until mesh.triangleCount) {
            fbuf.clear()
            fbuf.put(3)
            for (a in 0 until 3) fbuf.putInt(mesh.indices[t * 3 + a])
            bos.write(fbuf.array(), 0, 13)
        }
        bos.flush()
    }
}

/** Reads the binary PLY files produced by [PlyWriter]. */
object PlyReader {
    fun read(input: InputStream): MeshData {
        val din = DataInputStream(input.buffered(1 shl 16))
        val headerLines = ArrayList<String>()
        while (true) {
            val line = readAsciiLine(din) ?: throw IOException("Unexpected end of PLY header")
            headerLines += line.trim()
            if (line.trim() == "end_header") break
            if (headerLines.size > 200) throw IOException("PLY header too long")
        }
        if (headerLines.firstOrNull() != "ply") throw IOException("Not a PLY file")
        if (headerLines.none { it == "format binary_little_endian 1.0" }) {
            throw IOException("Only binary little-endian PLY files are supported")
        }
        var vertexCount = -1
        var faceCount = -1
        val vertexProps = ArrayList<String>()
        var current = ""
        for (l in headerLines) {
            val parts = l.split(' ').filter { it.isNotEmpty() }
            when {
                parts.size == 3 && parts[0] == "element" -> {
                    current = parts[1]
                    if (current == "vertex") vertexCount = parts[2].toInt()
                    if (current == "face") faceCount = parts[2].toInt()
                }
                parts.isNotEmpty() && parts[0] == "property" && current == "vertex" -> vertexProps += l
            }
        }
        val expected = listOf(
            "property float x", "property float y", "property float z",
            "property float nx", "property float ny", "property float nz",
            "property uchar red", "property uchar green", "property uchar blue",
        )
        if (vertexProps != expected || vertexCount < 0 || faceCount < 0) {
            throw IOException("Unsupported PLY layout (expected a CameraMapper3D export)")
        }

        val pos = FloatArray(vertexCount * 3)
        val nrm = FloatArray(vertexCount * 3)
        val col = ByteArray(vertexCount * 3)
        val vb = ByteArray(27)
        val bb = ByteBuffer.wrap(vb).order(ByteOrder.LITTLE_ENDIAN)
        for (i in 0 until vertexCount) {
            din.readFully(vb)
            bb.clear()
            for (a in 0 until 3) pos[i * 3 + a] = bb.getFloat()
            for (a in 0 until 3) nrm[i * 3 + a] = bb.getFloat()
            for (a in 0 until 3) col[i * 3 + a] = bb.get()
        }
        val idx = IntArray(faceCount * 3)
        val fb = ByteArray(12)
        val fbb = ByteBuffer.wrap(fb).order(ByteOrder.LITTLE_ENDIAN)
        for (t in 0 until faceCount) {
            val n = din.readUnsignedByte()
            if (n != 3) throw IOException("Only triangle faces are supported")
            din.readFully(fb)
            fbb.clear()
            for (a in 0 until 3) {
                val v = fbb.getInt()
                if (v < 0 || v >= vertexCount) throw IOException("Face index out of range")
                idx[t * 3 + a] = v
            }
        }
        return MeshData(pos, nrm, col, idx)
    }

    private fun readAsciiLine(din: DataInputStream): String? {
        val sb = StringBuilder()
        while (true) {
            val b = din.read()
            if (b < 0) return if (sb.isEmpty()) null else sb.toString()
            if (b == '\n'.code) return sb.toString()
            if (b != '\r'.code) sb.append(b.toChar())
            if (sb.length > 1024) throw IOException("PLY header line too long")
        }
    }
}

/**
 * Writes Wavefront OBJ. Vertex colours use the widely supported "v x y z r g b" extension
 * (read by Blender, MeshLab and CloudCompare); viewers that do not know it simply ignore the colours.
 */
object ObjWriter {
    fun write(mesh: MeshData, out: OutputStream) {
        val w = BufferedWriter(OutputStreamWriter(out, Charsets.US_ASCII), 1 shl 16)
        w.write("# Generated by CameraMapper3D. Units: metres. Y is up.\n")
        w.write("# ${mesh.vertexCount} vertices, ${mesh.triangleCount} triangles\n")
        val l = Locale.ROOT
        for (i in 0 until mesh.vertexCount) {
            w.write(
                String.format(
                    l, "v %.5f %.5f %.5f %.4f %.4f %.4f\n",
                    mesh.positions[i * 3], mesh.positions[i * 3 + 1], mesh.positions[i * 3 + 2],
                    (mesh.colors[i * 3].toInt() and 0xFF) / 255f,
                    (mesh.colors[i * 3 + 1].toInt() and 0xFF) / 255f,
                    (mesh.colors[i * 3 + 2].toInt() and 0xFF) / 255f,
                ),
            )
        }
        for (i in 0 until mesh.vertexCount) {
            w.write(String.format(l, "vn %.4f %.4f %.4f\n", mesh.normals[i * 3], mesh.normals[i * 3 + 1], mesh.normals[i * 3 + 2]))
        }
        for (t in 0 until mesh.triangleCount) {
            val a = mesh.indices[t * 3] + 1; val b = mesh.indices[t * 3 + 1] + 1; val c = mesh.indices[t * 3 + 2] + 1
            w.write("f $a//$a $b//$b $c//$c\n")
        }
        w.flush()
    }
}
